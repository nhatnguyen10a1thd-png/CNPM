(async () => {
  if (!state.demo || location.port !== '18084') throw new Error('Require isolated Phase04 demo');
  const results = [];
  const check = (name, passed) => results.push({ name, passed: !!passed });
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
  const settle = async element => {
    for (let i = 0; i < 100 && element.getAttribute('aria-busy') === 'true'; i++) await pause(50);
    if (element.getAttribute('aria-busy') === 'true') throw new Error('UI did not settle');
  };
  const fill = (form, values) => { for (const [name, value] of Object.entries(values)) form.elements[name].value = value; };
  const submit = async form => { form.requestSubmit(); await settle(form); };
  const signIn = async (identifier, password) => {
    authView('login'); fill($('login-form'), { identifier, password });
    await submit($('login-form')); await settle($('staff-view'));
  };
  const search = async keyword => { fill($('staff-search'), { keyword }); await submit($('staff-search')); await settle($('staff-view')); };
  await signIn('admin@lunea.test', 'DemoAdmin123');
  check('ADMIN login opens staff page', state.user?.roles.includes('ADMIN') && !$('staff-view').hidden);
  check('employee list loaded via actual API', state.employees.length >= 2 && $('employee-rows').querySelector('tr'));
  check('staff mutations require CSRF', (await fetch('/api/employees', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status === 403);
  $('add-employee').click();
  const form = $('employee-form');
  check('create requires password', form.elements.password.required && !form.checkValidity());
  const email = `browser-${Date.now()}@lunea.test`;
  fill(form, { fullName: 'Phase04 Browser Staff', email, password: 'BrowserStaff123' });
  const warehouse = state.roles.find(r => r.name === 'QLTK');
  const branch = state.stores.find(s => s.status === 'ACTIVE');
  const outside = state.stores.find(s => s.id !== branch.id);
  form.querySelector(`input[name="roleIds"][value="${warehouse.id}"]`).click();
  form.querySelector(`input[name="storeIds"][value="${branch.id}"]`).click();
  check('assigned store selects required primary', form.elements.primaryStoreId.required && Number(form.elements.primaryStoreId.value) === branch.id);
  form.requestSubmit();
  check('saving disables buttons while loading', form.getAttribute('aria-busy') === 'true' && [...form.querySelectorAll('button')].every(b => b.disabled));
  await settle(form);
  check('create UI reports success and closes modal', !$('employee-dialog').open && $('notice').textContent === 'Đã tạo nhân viên.');
  await search(email);
  const target = state.employees[0];
  check('search finds employee with primary role scope', state.employees.length === 1 && target.roleIds.includes(warehouse.id) && target.primaryStoreId === branch.id);
  check('response and table exclude credentials', !JSON.stringify(target).includes('password') && !$('employee-rows').textContent.includes('BrowserStaff123'));
  $('employee-rows').querySelector('[data-edit]').click();
  check('edit omits password to preserve credential', !form.elements.password.required && form.elements.password.value === '');
  fill(form, { fullName: 'Phase04 Edited Staff' }); await submit(form);
  check('edit UI persists profile', state.employees[0].fullName === 'Phase04 Edited Staff' && !$('employee-dialog').open);
  $('add-employee').click(); fill(form, { fullName: 'Duplicate Staff', email, password: 'BrowserStaff123' });
  await submit(form);
  check('duplicate shows controlled error and keeps form', $('employee-dialog').open && !$('employee-error').hidden && form.querySelector('[type="submit"]').disabled === false);
  $('cancel-employee').click();
  for (let i = 0; i < 11; i++) await api('/api/employees', { method: 'POST', body: { fullName: `Paging ${i}`, email: `paging-${i}-${Date.now()}@lunea.test`, password: 'PagingPass123', roleIds: [], storeIds: [] } });
  await search('');
  check('first page has 10 rows and next control', state.employees.length === 10 && state.pages === 2 && !$('next-page').disabled && $('prev-page').disabled);
  const firstIds = state.employees.map(e => e.id);
  $('next-page').click(); await settle($('staff-view'));
  check('next page changes rows and disables next', state.page === 1 && state.employees.length > 0 && state.employees.every(e => !firstIds.includes(e.id)) && $('next-page').disabled && !$('prev-page').disabled);
  $('prev-page').click(); await settle($('staff-view'));
  check('previous page restores rows', state.page === 0 && JSON.stringify(state.employees.map(e => e.id)) === JSON.stringify(firstIds));
  await search('no-matching-' + Date.now());
  check('empty search renders typed empty state', state.employees.length === 0 && $('employee-rows').textContent.includes('Không tìm thấy') && $('page-info').textContent.includes('Trang 0/0') && $('prev-page').disabled && $('next-page').disabled);
  $('roles-tab').click(); await settle($('roles-view'));
  const productRole = state.roles.find(r => r.name === 'QLSP');
  $('role-select').value = String(productRole.id); $('role-select').dispatchEvent(new Event('change'));
  const catalogPermission = state.permissions.find(p => p.code === 'CATALOG_MANAGE');
  $('permission-options').querySelector(`input[value="${catalogPermission.id}"]`).click(); await submit($('role-form'));
  check('grant UI revokes requested permission', !state.roles.find(r => r.id === productRole.id).permissionIds.includes(catalogPermission.id));
  $('permission-options').querySelector(`input[value="${catalogPermission.id}"]`).click(); await submit($('role-form'));
  check('grant UI restores requested permission', state.roles.find(r => r.id === productRole.id).permissionIds.includes(catalogPermission.id));
  $('role-select').value = String(state.roles.find(r => r.name === 'ADMIN').id); $('role-select').dispatchEvent(new Event('change'));
  check('reserved ADMIN grants locked in UI', $('save-role').disabled && $('permission-options').disabled);
  $('logout').click(); await settle(document.querySelector('header'));
  await signIn(email, 'BrowserStaff123');
  check('edited employee still authenticates with original password', state.user?.employeeId === target.id);
  check('nonmanager staff controls hidden', $('staff-tab').hidden && $('roles-tab').hidden);
  fill($('scope-form'), { storeId: branch.id }); await submit($('scope-form'));
  check('assigned branch succeeds in scope UI', $('scope-result').textContent.includes('Truy cập được phép'));
  fill($('scope-form'), { storeId: outside.id }); await submit($('scope-form'));
  check('unassigned branch returns visible permission error', $('notice').className === 'error' && $('scope-result').textContent === '');
  let denied; try { await api('/api/employees'); } catch (error) { denied = error; }
  check('hidden controls backed by server denial', denied?.status === 403);
  $('logout').click(); await settle(document.querySelector('header'));
  await signIn('admin@lunea.test', 'DemoAdmin123'); await search(email);
  const confirmation = window.confirm; window.confirm = () => true;
  try { $('employee-rows').querySelector('[data-deactivate]').click(); await settle($('staff-view')); }
  finally { window.confirm = confirmation; }
  check('deactivate preserves row and removes deactivate action', state.employees[0].status === 'INACTIVE' && !$('employee-rows').querySelector('[data-deactivate]'));
  $('logout').click(); await settle(document.querySelector('header'));
  await signIn(email, 'BrowserStaff123');
  check('deactivated employee login denied', !state.user && $('notice').className === 'error');
  await signIn('admin@lunea.test', 'DemoAdmin123'); await search('');
  return { passed: results.filter(r => r.passed).length, failed: results.filter(r => !r.passed).length, results };
})();
